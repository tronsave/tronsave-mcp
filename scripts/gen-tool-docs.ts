/**
 * Generates docs/TOOLS.md and docs/AGENT_GUIDE.md from the live server definitions so the
 * references can never drift. Run: `npm run docs:tools` (tests/docs/toolDocs.test.ts fails when stale).
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { AGENT_GUIDE_MARKDOWN } from "../src/mcp/agentGuide";
import { renderToolDocs } from "../src/tools/renderToolDocs";

const docsDir = path.resolve(__dirname, "..", "docs");
const header = "<!-- GENERATED by `npm run docs:tools` from src/mcp/agentGuide.ts. Do not edit by hand. -->\n\n";

writeFileSync(path.join(docsDir, "TOOLS.md"), renderToolDocs());
writeFileSync(path.join(docsDir, "AGENT_GUIDE.md"), header + AGENT_GUIDE_MARKDOWN);
console.log(`wrote ${docsDir}/TOOLS.md and AGENT_GUIDE.md`);

import { z } from "zod";
import type { ToolDefinition } from "./definitions/definition_type";
import { createAllTools } from "./definitions";

type JsonSchema = {
  type?: string | string[];
  description?: string;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  enum?: unknown[];
  anyOf?: JsonSchema[];
  default?: unknown;
  minimum?: number;
  maximum?: number;
  pattern?: string;
};

const AUTH_LABEL: Record<ToolDefinition["auth"]["mode"], string> = {
  public: "public",
  session: "api key (login or header)",
  "signature-session": "wallet signature",
};

const collectTools = (): ToolDefinition[] => {
  const handlers = new Proxy({}, { get: () => async () => ({ content: [] }) }) as never;
  // Same list the server registers, so new tool groups can never be left out of the docs.
  return createAllTools(handlers, handlers);
};

const typeOf = (schema: JsonSchema): string => {
  if (schema.enum) {
    return schema.enum.map((value) => `\`${String(value)}\``).join(" \\| ");
  }
  if (schema.anyOf) {
    return schema.anyOf.map(typeOf).filter((t) => t !== "null").join(" \\| ");
  }
  if (schema.type === "array") {
    return `${schema.items ? typeOf(schema.items) : "unknown"}[]`;
  }
  return Array.isArray(schema.type) ? schema.type.join(" \\| ") : (schema.type ?? "object");
};

const escape = (text: string): string => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

const paramRows = (schema: JsonSchema, prefix = ""): string[] => {
  const rows: string[] = [];
  const required = new Set(schema.required ?? []);
  for (const [name, prop] of Object.entries(schema.properties ?? {})) {
    const constraints = [
      prop.default !== undefined ? `default \`${JSON.stringify(prop.default)}\`` : "",
      prop.minimum !== undefined && prop.minimum > Number.MIN_SAFE_INTEGER ? `min ${prop.minimum}` : "",
      prop.maximum !== undefined && prop.maximum < Number.MAX_SAFE_INTEGER ? `max ${prop.maximum}` : "",
      prop.pattern?.startsWith("^T") ? "TRON address" : prop.pattern ? "hex" : "",
    ].filter(Boolean);
    rows.push(
      `| \`${prefix}${name}\` | ${typeOf(prop)} | ${required.has(name) ? "yes" : "no"} | ${escape(prop.description ?? "")}${
        constraints.length ? ` (${constraints.join(", ")})` : ""
      } |`,
    );
    if (prop.type === "object" && prop.properties) {
      rows.push(...paramRows(prop, `${prefix}${name}.`));
    }
  }
  return rows;
};

const flags = (tool: ToolDefinition): string => {
  const a = tool.annotations ?? {};
  return [
    a.readOnlyHint ? "read-only" : "write",
    a.destructiveHint ? "destructive" : "",
    a.idempotentHint ? "idempotent" : "",
  ]
    .filter(Boolean)
    .join(", ");
};

export const renderToolDocs = (): string => {
  const tools = collectTools();
  const lines: string[] = [
    "<!-- GENERATED by `npm run docs:tools` from src/tools/definitions. Do not edit by hand. -->",
    "",
    "# TronSave MCP — Tool Reference",
    "",
    `${tools.length} tools. Auth: **public** (no login), **api key** (\`tronsave_login\` with \`apiKey\` or header \`Authorization: ApiKey <key>\`), **wallet signature** (\`tronsave_get_sign_message\` → \`tronsave_login\` with \`signature\`).`,
    "",
    "Errors are returned as `isError: true` with text `{\"error\":{\"code\",\"message\",\"retryable\",\"hint\"}}` — see [AGENT_GUIDE.md](AGENT_GUIDE.md#error-codes).",
    "",
    "| Tool | Auth | Kind |",
    "|---|---|---|",
    ...tools.map((tool) => `| [\`${tool.name}\`](#${tool.name}) | ${AUTH_LABEL[tool.auth.mode]} | ${flags(tool)} |`),
    "",
  ];

  for (const tool of tools) {
    const input = z.toJSONSchema(tool.inputSchema, { io: "input", unrepresentable: "any" }) as JsonSchema;
    const output = z.toJSONSchema(tool.outputSchema, { unrepresentable: "any" }) as JsonSchema;
    const inputRows = paramRows(input);
    lines.push(
      `## ${tool.name}`,
      "",
      `**${tool.title}** · auth: ${AUTH_LABEL[tool.auth.mode]} · ${flags(tool)}`,
      "",
      tool.description,
      "",
      "**Input**",
      "",
      ...(inputRows.length
        ? ["| Field | Type | Required | Description |", "|---|---|---|---|", ...inputRows]
        : ["_No arguments._"]),
      "",
      "**Output (`structuredContent`)**",
      "",
      "| Field | Type | Description |",
      "|---|---|---|",
      ...Object.entries(output.properties ?? {}).map(
        ([name, prop]) => `| \`${name}\` | ${typeOf(prop)} | ${escape(prop.description ?? "")} |`,
      ),
      "",
    );
  }
  return `${lines.join("\n").trimEnd()}\n`;
};
